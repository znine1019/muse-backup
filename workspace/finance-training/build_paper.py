# ---------- 工具函数 ----------
def style_run(run, size=12, bold=False, font='宋体'):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = font
    rPr = run.element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:eastAsia'), font)

def para_before(ref, text='', bold=False, size=12, indent=True, align=None, space_after=4):
    p = ref.insert_paragraph_before()
    if indent:
        p.paragraph_format.first_line_indent = Pt(size * 2)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.5
    if align is not None:
        p.alignment = align
    if text:
        r = p.add_run(text)
        style_run(r, size=size, bold=bold)
    return p

def answer_head(ref):
    """每个小问的答案开头：加粗的“答：”起头段，后续文字接在同一段或新段。"""
    return para_before(ref, '', indent=False)

def add_text_run(p, text, bold=False, size=12):
    r = p.add_run(text)
    style_run(r, size=size, bold=bold)
    return r

def set_cell(cell, text, bold=False, size=10.5, align=WD_ALIGN_PARAGRAPH.CENTER):
    cell.text = ''
    p = cell.paragraphs[0]
    p.alignment = align
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.line_spacing = 1.15
    r = p.add_run(str(text))
    style_run(r, size=size, bold=bold)

def table_borders(tbl):
    tblPr = tbl._tbl.tblPr
    borders = OxmlElement('w:tblBorders')
    for edge in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        el = OxmlElement(f'w:{edge}')
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), '4')
        el.set(qn('w:space'), '0')
        el.set(qn('w:color'), '000000')
        borders.append(el)
    tblPr.append(borders)

def table_before(ref, headers, rows, first_col_left=True):
    tbl = doc.add_table(rows=1, cols=len(headers))
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    tbl.autofit = True
    for j, h in enumerate(headers):
        set_cell(tbl.rows[0].cells[j], h, bold=True)
    for row in rows:
        cells = tbl.add_row().cells
        for j, v in enumerate(row):
            al = WD_ALIGN_PARAGRAPH.LEFT if (j == 0 and first_col_left) else WD_ALIGN_PARAGRAPH.CENTER
            set_cell(cells[j], v, align=al)
    table_borders(tbl)
    ref._p.addprevious(tbl._tbl)
    return tbl

def caption(ref, text):
    return para_before(ref, text, bold=True, indent=False, space_after=2)

